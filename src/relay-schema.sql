CREATE TABLE IF NOT EXISTS visitors(id TEXT PRIMARY KEY,csrf TEXT NOT NULL,view TEXT NOT NULL,touched INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS work(id TEXT PRIMARY KEY,owner TEXT NOT NULL,kind TEXT NOT NULL,command TEXT NOT NULL,status TEXT NOT NULL,created INTEGER NOT NULL,lease INTEGER NOT NULL,error TEXT);
CREATE INDEX IF NOT EXISTS work_owner ON work(owner,created);
CREATE INDEX IF NOT EXISTS work_status ON work(status,created);
CREATE TABLE IF NOT EXISTS service(id INTEGER PRIMARY KEY,at INTEGER NOT NULL);
